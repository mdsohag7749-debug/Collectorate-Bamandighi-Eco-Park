🔌 API এন্ডপয়েন্ট (API Endpoints):

1. Contact সাবমিট করা (Submit contact form):
   POST /api/contact
   Body: {
     "name": "নাম",
     "phone": "ফোন",
     "email": "ইমেইল",
     "subject": "বিষয়",
     "message": "বার্তা"
   }

2. সব Contact পেতে (Get all contacts):
   GET /api/contacts

3. একটি Contact এর স্থিতি আপডেট করা (Update status):
   PUT /api/contact/:id/status
   Body: { "status": "নতুন|পেন্ডিং|উত্তর দেওয়া হয়েছে" }

4. Contact মুছে ফেলা (Delete contact):
   DELETE /api/contact/:id

5. পরিসংখ্যান পেতে (Get stats):
   GET /api/stats

6. হেলথ চেক (Health check):
   GET /api/health

