🐛 সমস্যা সমাধান (Troubleshooting):

সমস্যা: "Cannot POST /api/contact"
সমাধান: নিশ্চিত করুন backend সার্ভার চলছে (npm run server)

সমস্যা: Contact ফর্ম সাবমিট করছে না
সমাধান: Browser console চেক করুন (F12)। 
         নিশ্চিত করুন সার্ভার আছে।

সমস্যা: Admin panel খালি দেখাচ্ছে
সমাধান: কন্টাক্ট ফর্ম থেকে কমপক্ষে একটি বার্তা পাঠান

সমস্যা: Port 5000 এ ব্যবহারে আছে
সমাধান: server-backend.js এ PORT পরিবর্তন করুন

